"""``probe profile``: check a profile file, or scaffold one from a scan report."""

import json
from pathlib import Path
from typing import Annotated

import typer
from pydantic import ValidationError

from probe.config.profile import ProfileError, load_profile, parse_profile
from probe.report.models import ScanReport
from probe.util.sanitize_console import sanitize_console

app = typer.Typer(help="Validate and scaffold scan profiles.", no_args_is_help=True)
_COMMENT_MAX = 100


def _one_line(text: str) -> str:
    """Server-provided text as a safe single-line YAML comment."""
    flat = " ".join(sanitize_console(text).split())
    return flat if len(flat) <= _COMMENT_MAX else flat[: _COMMENT_MAX - 1] + "…"


@app.command()
def validate(
    paths: Annotated[list[Path], typer.Argument(help="Profile files to check.")],
) -> None:
    """Check profile files; exit 2 if any is invalid."""
    failed = False
    for path in paths:
        try:
            profile = load_profile(path)
        except ProfileError as exc:
            typer.echo(f"invalid {exc}", err=True)
            failed = True
            continue
        extras = []
        if len(profile.auth.identities) >= 2:
            extras.append(f"{len(profile.auth.identities)} identities")
        if profile.tools:
            extras.append(f"{len(profile.tools)} tool overrides")
        typer.echo(f"ok {path}" + (f" ({', '.join(extras)})" if extras else ""))
    raise typer.Exit(2 if failed else 0)


def scaffold(report: ScanReport | None) -> str:
    """A starting profile as YAML text: every tool listed with its inferred kind, to adjust."""
    name = sanitize_console(report.target.name) if report else "my-server"
    transport = report.target.transport.value if report else "stdio"
    lines = [
        "# Generated by `probe profile init`. Edit it, then run `probe profile validate`.",
        "version: 1",
        f"name: {json.dumps(name)}",
        "target:",
        f"  transport: {transport}",
        '  # command: ["my-server", "--stdio"]   # what starts the server',
        "  # env: {LOG_LEVEL: debug}",
        "  # secrets:",
        '  #   API_TOKEN: {value: "probe_fake_{token}", real: false}',
    ]
    if report is None or not report.tools:
        lines += ["tools: {}   # override a tool's kind: name: {kind: read|write|destructive|exec}"]
    else:
        lines += [
            "tools:   # kinds Probe inferred; correct any that are wrong",
        ]
        for tool in report.tools:
            origin = f"{tool.classification_source}: {_one_line(tool.classification_reason)}"
            lines.append(f"  {json.dumps(tool.name)}: {{kind: {tool.kind}}}   # {origin}")
    lines += [
        "# inputs:                 # known-good arguments per tool",
        "#   read_file: [{path: /data/allowed/readme.md}]",
        "# auth:",
        "#   type: bearer          # two identities enable the cache-scope check",
        "#   identities:",
        '#     - {name: alice, token: "probe_fake_alice_{token}"}',
        '#     - {name: bob, token: "probe_fake_bob_{token}"}',
        "# checks:",
        '#   skip: {safety.some_check: "why it does not apply"}',
        "# notes: free text shown in the report",
    ]
    text = "\n".join(lines) + "\n"
    parse_profile(text, "the generated profile")  # what we write must be valid
    return text


@app.command()
def init(
    from_report: Annotated[
        Path | None, typer.Option(help="A report.json from a previous scan.")
    ] = None,
    out: Annotated[Path | None, typer.Option(help="Write here instead of printing.")] = None,
    force: Annotated[bool, typer.Option(help="Overwrite an existing --out file.")] = False,
) -> None:
    """Scaffold a profile, listing every tool from a previous scan with its inferred kind."""
    report: ScanReport | None = None
    if from_report is not None:
        try:
            report = ScanReport.model_validate_json(from_report.read_text(encoding="utf-8"))
        except (OSError, ValidationError, ValueError) as exc:
            typer.echo(f"probe: cannot read report {from_report}: {type(exc).__name__}", err=True)
            raise typer.Exit(2) from exc
    text = scaffold(report)
    if out is None:
        typer.echo(text, nl=False)
        return
    if out.exists() and not force:
        typer.echo(f"probe: {out} exists; use --force to overwrite", err=True)
        raise typer.Exit(2)
    out.write_text(text, encoding="utf-8")
    typer.echo(f"wrote {out}")
