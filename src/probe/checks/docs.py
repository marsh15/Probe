"""The check catalog as documentation, generated from each check's own metadata.

``docs/checks.md`` is this module's output; a test fails if the file is stale, so the docs cannot
drift from the code.
"""

from collections.abc import Iterable

import probe.checks.behavior
import probe.checks.official
import probe.checks.operability
import probe.checks.protocol
import probe.checks.safety
import probe.checks.schema  # noqa: F401 - registers the schema checks
from probe.checks.base import Check
from probe.checks.registry import REGISTRY
from probe.engine.outcomes import CheckMeta, Family

FAMILY_BLURB = {
    Family.PROTOCOL: "Does the server speak MCP the way the specification says?",
    Family.SCHEMA: "Are the tool definitions and list results the server publishes well formed?",
    Family.BEHAVIOR: "Does the server behave correctly when its tools are called?",
    Family.SAFETY: "Can the server be made to do something it should not?",
    Family.OPERABILITY: "Can the server be run and observed in production?",
}


def builtin_checks() -> list[type[Check]]:
    """The checks shipped with Probe, in run order (plugins from entry points are excluded)."""
    return [c for c in REGISTRY if c.__module__.startswith("probe.checks.")]


_MODE_ORDER = ("quick", "standard", "deep")


def _modes(meta: CheckMeta) -> str:
    return ", ".join(m for m in _MODE_ORDER if m in meta.modes)


def _join(values: Iterable[object]) -> str:
    return ", ".join(sorted(str(getattr(v, "value", v)) for v in values)) or "none"


def _row(meta: CheckMeta) -> str:
    cells = [
        f"[`{meta.id}`](#{meta.id.replace('.', '')})",
        meta.severity.value,
        meta.phase,
        _join(meta.eras),
        _join(meta.transports),
        _modes(meta),
        meta.title,
    ]
    return "| " + " | ".join(cells) + " |"


def check_markdown(meta: CheckMeta) -> str:
    """The detail section for one check (also what `probe checks show` prints)."""
    return "\n".join(_section(meta)).rstrip() + "\n"


def _section(meta: CheckMeta) -> list[str]:
    lines = [
        f"### {meta.id}",
        "",
        f"**{meta.title}**",
        "",
        f"- Severity: {meta.severity.value} (catalog; a finding may be reported at another level)",
        f"- Phase: {meta.phase}; modes: {_modes(meta)}",
        f"- Eras: {_join(meta.eras)}; transports: {_join(meta.transports)}",
        f"- Needs: {_join(meta.requires)}",
    ]
    if meta.min_version:
        lines.append(f"- Protocol {meta.min_version} or later")
    lines.append(f"- Disclosure: {meta.disclosure.value}")
    if meta.spec_refs:
        lines.append(f"- Spec: {', '.join(meta.spec_refs)}")
    lines += [
        "",
        f"**Why it matters.** {meta.rationale}",
        "",
        f"**How to fix.** {meta.remediation}",
        "",
    ]
    return lines


def render_markdown(checks: Iterable[type[Check]] | None = None) -> str:
    chosen = list(builtin_checks() if checks is None else checks)
    metas = [c.meta for c in chosen]
    lines = [
        "# Check catalog",
        "",
        "<!-- Generated by `probe checks list --format md`. Do not edit by hand. -->",
        "",
        f"Probe ships {len(metas)} checks. Each runs in a fixed phase, is judged by what the",
        "server does, and reports PASS, FAIL, NOT_APPLICABLE, SKIPPED or ERROR. Severity here is",
        "the catalog severity, which sets the check's weight; an individual finding may be",
        "reported at a different level.",
        "",
    ]
    for family in Family:
        group = [m for m in metas if m.family is family]
        if not group:
            continue
        lines += [
            f"## {family.value.capitalize()}",
            "",
            FAMILY_BLURB[family],
            "",
            "| Check | Severity | Phase | Eras | Transports | Modes | What it checks |",
            "|---|---|---|---|---|---|---|",
            *[_row(m) for m in group],
            "",
        ]
    lines += ["## Details", ""]
    for meta in metas:
        lines += _section(meta)
    return "\n".join(lines).rstrip() + "\n"
